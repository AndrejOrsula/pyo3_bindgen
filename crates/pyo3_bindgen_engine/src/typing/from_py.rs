use super::Type;
use crate::{
    runtime_sentinels::{self, StdlibModule},
    PyBindgenError, Result,
};
use pyo3::prelude::*;
use std::str::FromStr;

// `Type::from_str` has a large match frame; keep this below the point where Rust's
// smaller test/worker thread stacks overflow before the guard can report an error.
const MAX_TYPE_PARSE_DEPTH: usize = 64;

std::thread_local! {
    static TYPE_PARSE_DEPTH: std::cell::Cell<usize> = const { std::cell::Cell::new(0) };
}

struct TypeParseDepthGuard;

impl TypeParseDepthGuard {
    fn enter() -> Result<Self> {
        TYPE_PARSE_DEPTH.with(|depth| {
            let current = depth.get();
            if current >= MAX_TYPE_PARSE_DEPTH {
                return Err(PyBindgenError::CodegenError(format!(
                    "type annotation nesting exceeds the supported depth \
                     ({MAX_TYPE_PARSE_DEPTH})"
                )));
            }
            depth.set(current + 1);
            Ok(Self)
        })
    }
}

impl Drop for TypeParseDepthGuard {
    fn drop(&mut self) {
        TYPE_PARSE_DEPTH.with(|depth| {
            let current = depth.get();
            debug_assert!(current > 0, "type parse depth guard underflow");
            depth.set(current.saturating_sub(1));
        });
    }
}

impl TryFrom<pyo3::Bound<'_, pyo3::types::PyAny>> for Type {
    type Error = PyBindgenError;
    fn try_from(value: pyo3::Bound<pyo3::types::PyAny>) -> Result<Self> {
        let _depth_guard = TypeParseDepthGuard::enter()?;
        match value {
            // None -> Unknown type
            none if none.is_none() => Ok(Self::Unknown),
            ellipsis if ellipsis.is_exact_instance_of::<pyo3::types::PyEllipsis>() => {
                Ok(Self::PyEllipsis)
            }
            // Handle PyType
            t if t.is_instance_of::<pyo3::types::PyType>() => {
                let x = t.cast_into::<pyo3::types::PyType>().unwrap();
                Self::try_from(x)
            }
            // PEP 585 parameterized built-ins expose stable structural metadata.
            union if has_runtime_type(&union, "types", "UnionType") => Self::from_union_args(union),
            alias if has_runtime_type(&alias, "types", "GenericAlias") => {
                Self::from_parameterized(alias)
            }
            // Handle typing
            typing if is_genuine_typing_runtime(&typing) => Self::from_typing(typing),
            // String annotations, including forward references, have stable semantics.
            string if string.is_instance_of::<pyo3::types::PyString>() => {
                Self::from_str(string.cast::<pyo3::types::PyString>().unwrap().to_str()?)
            }
            // Arbitrary annotation values can embed process-local addresses in `repr`.
            // Treating that display as a type made both generated bytes and reports
            // nondeterministic, so an opaque value is deliberately untyped.
            _ => Ok(Self::Unknown),
        }
    }
}

impl TryFrom<pyo3::Bound<'_, pyo3::types::PyType>> for Type {
    type Error = PyBindgenError;
    fn try_from(value: pyo3::Bound<pyo3::types::PyType>) -> Result<Self> {
        Ok(match value {
            t if is_python_enum_type(&t)? => stable_python_type_name(&t)
                .map(Self::Other)
                .unwrap_or(Self::Unknown),

            // Primitives
            t if is_exact_python_type::<pyo3::types::PyBool>(&t) => Self::PyBool,
            t if is_exact_python_type::<pyo3::types::PyByteArray>(&t) => Self::PyByteArray,
            t if is_exact_python_type::<pyo3::types::PyBytes>(&t) => Self::PyBytes,
            t if is_exact_python_type::<pyo3::types::PyFloat>(&t) => Self::PyFloat,
            t if is_exact_python_type::<pyo3::types::PyInt>(&t) => Self::PyInt,
            t if is_exact_python_type::<pyo3::types::PyString>(&t) => Self::PyString,

            // Collections
            t if is_exact_python_type::<pyo3::types::PyDict>(&t) => Self::PyDict {
                key_type: Box::new(Self::Unknown),
                value_type: Box::new(Self::Unknown),
            },
            t if is_exact_python_type::<pyo3::types::PyFrozenSet>(&t) => {
                Self::PyFrozenSet(Box::new(Self::Unknown))
            }
            t if is_exact_python_type::<pyo3::types::PyList>(&t) => {
                Self::PyList(Box::new(Self::Unknown))
            }
            t if is_exact_python_type::<pyo3::types::PySet>(&t) => {
                Self::PySet(Box::new(Self::Unknown))
            }
            t if is_exact_python_type::<pyo3::types::PyTuple>(&t) => {
                Self::PyTuple(vec![Self::Unknown])
            }

            // Additional types - std
            t if is_exact_python_type::<pyo3::types::PySlice>(&t) => Self::PySlice,

            // Additional types - num-complex
            t if is_exact_python_type::<pyo3::types::PyComplex>(&t) => Self::PyComplex,

            // Additional types - datetime
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyDateTime>(&t) => Self::PyDateTime,
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyDate>(&t) => Self::PyDate,
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyDelta>(&t) => Self::PyDelta,
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyTime>(&t) => Self::PyTime,
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyTzInfo>(&t) => Self::PyTzInfo,

            // Python-specific types
            t if is_exact_python_type::<pyo3::types::PyCapsule>(&t) => Self::PyCapsule,
            t if is_exact_python_type::<pyo3::types::PyCFunction>(&t) => Self::PyCFunction,
            #[cfg(not(Py_LIMITED_API))]
            t if is_exact_python_type::<pyo3::types::PyCode>(&t) => Self::PyCode,
            #[cfg(all(not(Py_LIMITED_API), not(any(PyPy, GraalPy))))]
            t if is_exact_python_type::<pyo3::types::PyFrame>(&t) => Self::PyFrame,
            #[cfg(all(not(Py_LIMITED_API), not(PyPy)))]
            t if is_exact_python_type::<pyo3::types::PyFunction>(&t) => Self::PyFunction {
                param_types: vec![Self::PyEllipsis],
                return_annotation: Box::new(Self::Unknown),
            },
            t if is_exact_python_type::<pyo3::types::PyModule>(&t) => Self::PyModule,
            #[cfg(not(PyPy))]
            t if is_exact_python_type::<pyo3::types::PySuper>(&t) => Self::PySuper,
            t if is_exact_python_type::<pyo3::types::PyTraceback>(&t) => Self::PyTraceback,
            t if is_exact_python_type::<pyo3::types::PyType>(&t) => Self::PyType,

            // Custom type identity comes from Python's stable metadata. Calling
            // `str(type)` invokes a user-controlled metaclass and can embed an
            // address or other process-local state in generated output.
            _ => match stable_python_type_name(&value) {
                Some(name) => Self::from_str(&name)?,
                None => Self::Unknown,
            },
        })
    }
}

fn is_exact_python_type<T: pyo3::PyTypeInfo>(value: &pyo3::Bound<'_, pyo3::types::PyType>) -> bool {
    value.is(pyo3::types::PyType::new::<T>(value.py()))
}

fn is_python_enum_type(value: &pyo3::Bound<pyo3::types::PyType>) -> Result<bool> {
    let py = value.py();
    Ok(value.is_subclass(enum_class(py)?.as_any())?)
}

/// The `enum.Enum` base class, imported once per interpreter process. `is_python_enum_type`
/// is the first check for *every* converted type, so re-importing `enum` per call was pure
/// overhead on plain `int`/`str`/custom-class annotations.
fn enum_class(py: Python<'_>) -> PyResult<Bound<'_, PyAny>> {
    runtime_sentinels::attr(py, StdlibModule::Enum, "Enum")
}

fn stable_python_type_name(value: &pyo3::Bound<'_, pyo3::types::PyType>) -> Option<String> {
    let py = value.py();
    let module = value
        .getattr(pyo3::intern!(py, "__module__"))
        .ok()?
        .extract::<String>()
        .ok()?;
    let qualname = value
        .getattr(pyo3::intern!(py, "__qualname__"))
        .ok()?
        .extract::<String>()
        .ok()?;
    if qualname.is_empty() {
        None
    } else if module.is_empty() || module == "builtins" {
        Some(qualname)
    } else {
        Some(format!("{module}.{qualname}"))
    }
}

fn has_runtime_type(value: &pyo3::Bound<'_, pyo3::types::PyAny>, module: &str, name: &str) -> bool {
    let py = value.py();
    let runtime_type = value.get_type();
    // Canonical identity remains reliable when aliases expose different metadata. Python 3.14,
    // for example, aliases `types.UnionType` to `typing.Union`. Read the pre-target
    // module snapshot so later stdlib monkeypatches cannot change type classification.
    let runtime_module = match module {
        "types" => StdlibModule::Types,
        "typing" => StdlibModule::Typing,
        _ => return false,
    };
    runtime_sentinels::attr(py, runtime_module, name)
        .is_ok_and(|canonical_type| runtime_type.is(&canonical_type))
}

fn is_genuine_typing_runtime(value: &pyo3::Bound<'_, pyo3::types::PyAny>) -> bool {
    let py = value.py();
    let runtime_type = value.get_type();
    let Ok(runtime_module) = runtime_type
        .getattr(pyo3::intern!(py, "__module__"))
        .and_then(|module| module.extract::<String>())
    else {
        return false;
    };
    // CPython 3.14 made `typing.ForwardRef` an exact alias of
    // `annotationlib.ForwardRef`. The canonical `typing.<runtime_name>` identity check
    // below still rejects unrelated or spoofed annotationlib classes.
    if !matches!(runtime_module.as_str(), "typing" | "annotationlib") {
        return false;
    }
    let Ok(runtime_name) = runtime_type
        .getattr(pyo3::intern!(py, "__name__"))
        .and_then(|name| name.extract::<String>())
    else {
        return false;
    };
    runtime_sentinels::attr(py, StdlibModule::Typing, runtime_name.as_str())
        .is_ok_and(|canonical_type| runtime_type.is(&canonical_type))
}

impl Type {
    fn from_typing(value: pyo3::Bound<pyo3::types::PyAny>) -> Result<Self> {
        let py = value.py();
        debug_assert!(is_genuine_typing_runtime(&value));

        if has_runtime_type(&value, "typing", "ForwardRef") {
            let forward_arg = value
                .getattr(pyo3::intern!(py, "__forward_arg__"))?
                .extract::<String>()?;
            Self::from_str(&forward_arg)
        } else if value.hasattr(pyo3::intern!(py, "__origin__"))? {
            // Python 3.8 represents bare aliases such as `typing.List` as if
            // they had the synthetic argument `~T`; newer interpreters expose
            // no args. A genuine typing object's stable spelling distinguishes
            // the bare alias from an explicit `typing.List[T]` subscription.
            if value.to_string().contains('[') {
                Self::from_parameterized(value)
            } else {
                Self::try_from(value.getattr(pyo3::intern!(py, "__origin__"))?)
            }
        } else {
            // Handle everything else as string
            Type::from_str(&value.to_string())
        }
    }

    fn from_parameterized(value: pyo3::Bound<'_, pyo3::types::PyAny>) -> Result<Self> {
        let py = value.py();
        let wrapping_type = Self::try_from(value.getattr(pyo3::intern!(py, "__origin__"))?)?;
        let Ok(inner_types) = value
            .getattr(pyo3::intern!(py, "__args__"))
            .and_then(|inner_types| Ok(inner_types.cast_into::<pyo3::types::PyTuple>()?))
        else {
            return Ok(wrapping_type);
        };
        let inner_types = inner_types
            .iter()
            .map(Self::try_from)
            .collect::<Result<Vec<_>>>()?;
        if inner_types.is_empty() {
            return Ok(wrapping_type);
        }

        Ok(match wrapping_type {
            Self::Union(..) => Self::union_from(inner_types),
            Self::Optional(..) => Self::union_from(vec![inner_types[0].clone(), Self::PyNone]),
            Self::PyDict { .. } if inner_types.len() == 2 => Self::PyDict {
                key_type: Box::new(inner_types[0].clone()),
                value_type: Box::new(inner_types[1].clone()),
            },
            Self::PyDict { .. } => Self::PyDict {
                key_type: Box::new(Self::Unknown),
                value_type: Box::new(Self::Unknown),
            },
            Self::PyFrozenSet(..) => Self::PyFrozenSet(Box::new(inner_types[0].clone())),
            Self::PyList(..) => Self::PyList(Box::new(inner_types[0].clone())),
            Self::PySet(..) => Self::PySet(Box::new(inner_types[0].clone())),
            Self::PyTuple(..) => Self::PyTuple(inner_types),
            Self::PyFunction { .. } => Self::PyFunction {
                param_types: match inner_types.len() {
                    1 => Vec::default(),
                    _ => inner_types[..inner_types.len() - 1].to_owned(),
                },
                return_annotation: Box::new(
                    inner_types
                        .last()
                        .unwrap_or_else(|| unreachable!())
                        .to_owned(),
                ),
            },
            // `type[T]` / `typing.Type[T]` annotates a class object, not an
            // instance of `T`; the type parameter does not change extraction.
            Self::PyType => Self::PyType,
            _ => wrapping_type,
        })
    }

    fn from_union_args(value: pyo3::Bound<'_, pyo3::types::PyAny>) -> Result<Self> {
        let py = value.py();
        let inner_types = value
            .getattr(pyo3::intern!(py, "__args__"))?
            .cast_into::<pyo3::types::PyTuple>()
            .map_err(pyo3::PyErr::from)?
            .iter()
            .map(Self::try_from)
            .collect::<Result<Vec<_>>>()?;
        Ok(Self::union_from(inner_types))
    }

    fn union_from(inner_types: Vec<Self>) -> Self {
        fn push_normalized(inner: Type, distinct: &mut Vec<Type>) {
            match inner {
                Type::Union(members) => {
                    for member in members {
                        push_normalized(member, distinct);
                    }
                }
                Type::Optional(inner) => {
                    push_normalized(*inner, distinct);
                    push_normalized(Type::PyNone, distinct);
                }
                inner if !distinct.contains(&inner) => distinct.push(inner),
                _ => {}
            }
        }

        let mut distinct = Vec::with_capacity(inner_types.len());
        for inner in inner_types {
            push_normalized(inner, &mut distinct);
        }
        match distinct.as_slice() {
            [] => Self::Unknown,
            [only] => only.clone(),
            [first, second] if first == &Self::PyNone => Self::Optional(Box::new(second.clone())),
            [first, second] if second == &Self::PyNone => Self::Optional(Box::new(first.clone())),
            _ => Self::Union(distinct),
        }
    }
}

impl std::str::FromStr for Type {
    type Err = PyBindgenError;
    fn from_str(value: &str) -> Result<Self> {
        let _depth_guard = TypeParseDepthGuard::enter()?;
        let value = value.trim();
        validate_balanced_brackets(value)?;
        if let Some(unquoted) = strip_exact_quoted_payload(value) {
            return Self::from_str(unquoted);
        }
        if let Some(forward_arg) = strip_textual_forward_ref(value) {
            return Self::from_str(forward_arg);
        }

        if let Some(annotated_args) = strip_named_generic(
            value,
            &[
                "Annotated",
                "typing.Annotated",
                "typing_extensions.Annotated",
            ],
        ) {
            let annotated_args =
                split_nonempty_top_level(annotated_args, ',', true, "Annotated", value)?;
            if annotated_args.len() < 2 {
                return Err(PyBindgenError::CodegenError(format!(
                    "Invalid Annotated annotation '{value}' \
                     (expected a wrapped type and at least one metadata argument)"
                )));
            }
            return Self::from_str(&annotated_args[0]);
        }

        Ok(match value {
            "Any" => Self::PyAny,

            // Primitives
            "bool" => Self::PyBool,
            "bytearray" => Self::PyByteArray,
            "bytes" => Self::PyBytes,
            "float" => Self::PyFloat,
            "int" => Self::PyInt,
            "str" => Self::PyString,

            // Enums
            //
            // PEP 604 unions (`X | Y`). The split must be bracket-aware and operate on
            // **top-level** `|` only, so that a `|` nested inside a container's type
            // arguments (e.g. `dict[str, int | float]`) is left for the container arm
            // below to recurse into — splitting it here would mangle the container
            // (`["dict[str, int", "float]"]`) and abort generation. A `X | None` shape
            // lowers to `Optional<X>`; a genuine multi-type union (no `None`) has no
            // faithful Rust type, so it falls back to the untyped `Union` (which lowers
            // to `PyAny`) rather than aborting.
            r#union if has_top_level(r#union, '|') => {
                let parts = split_nonempty_top_level(r#union, '|', false, "union", r#union)?;
                let inner_types = parts
                    .iter()
                    .map(|part| Self::from_str(part))
                    .collect::<Result<Vec<_>>>()?;
                // Shared with the live-object path (`from_union_args`/`from_parameterized`)
                // so a string annotation and its equivalent runtime object normalize
                // (dedup + single-element/`None`-pair collapse) to the identical `Type`.
                Self::union_from(inner_types)
            }
            "Union" => Self::Union(vec![Self::Unknown]),
            optional if optional.starts_with("Optional[") && optional.ends_with(']') => {
                // Unlike ordinary subscriptions, `typing.Optional[int,]` passes a
                // one-tuple to Optional and Python rejects it. Keep that distinction
                // while still requiring exactly one ordinary argument.
                let inner = single_generic_argument(optional, "Optional", false, "Optional")?;
                let inner_type = Self::from_str(&inner)?;
                Self::union_from(vec![inner_type, Self::PyNone])
            }
            // Pre-PEP-604 `typing.Union[X, Y, ...]`. This is the only textual spelling
            // for a forward-reference string (e.g. under `from __future__ import
            // annotations`) or an external-IR schema annotation, so it must be handled
            // here rather than relying on the live-object `__args__` path. Split on
            // top-level commas (mirrors the `Callable[`/`dict[`/`tuple[` arms below) and
            // reuse `union_from` so the result matches the live-object path exactly.
            union_generic
                if union_generic.starts_with("Union[") && union_generic.ends_with(']') =>
            {
                let inner_types = union_generic
                    .strip_prefix("Union[")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix(']')
                    .unwrap_or_else(|| unreachable!());
                let inner_types = split_nonempty_top_level(inner_types, ',', true, "Union", value)?;
                let inner_types = inner_types
                    .iter()
                    .map(|x| Self::from_str(x))
                    .collect::<Result<Vec<_>>>()?;
                Self::union_from(inner_types)
            }
            "" | "None" | "NoneType" => Self::PyNone,

            // Collections
            // CR5: generic collection-protocol container annotation. Only an external
            // IR provider emits `Collection[<elem>]` (the live path emits `list[...]`),
            // so this branch never fires on the live introspection path.
            collection if collection.starts_with("Collection[") && collection.ends_with(']') => {
                let inner = single_generic_argument(collection, "Collection", true, "Collection")?;
                let inner_type = Self::from_str(&inner)?;
                Self::Collection(Box::new(inner_type))
            }
            // CR7: fixed-shape numeric array annotation `Array[<elem>; d1, d2, ...]`.
            // Only an external IR provider emits this (the live path emits
            // `list[...]` for arrays), so this branch never fires on the live
            // introspection path and the live output stays byte-identical.
            fixed_array
                if fixed_array.starts_with("Array[")
                    && fixed_array.ends_with(']')
                    // The `;` separator is what makes this annotation IR-exclusive:
                    // Python subscript syntax cannot contain it, so a live annotation
                    // like `Array[float]` falls through to `Other` instead of aborting
                    // generation here.
                    && fixed_array.contains(';') =>
            {
                let inner = fixed_array
                    .strip_prefix("Array[")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix(']')
                    .unwrap_or_else(|| unreachable!());
                let parts = split_nonempty_top_level(inner, ';', false, "fixed-array", value)?;
                let [elem_str, dims_str] = parts.as_slice() else {
                    return Err(PyBindgenError::CodegenError(format!(
                        "Invalid fixed-array annotation '{value}' \
                         (expected exactly one top-level separator: \
                         'Array[<elem>; d1, d2, ...]')"
                    )));
                };
                let dims = dims_str
                    .split(',')
                    .map(str::trim)
                    .map(|dim| {
                        dim.parse::<usize>().map_err(|_| {
                            PyBindgenError::CodegenError(format!(
                                "Invalid fixed-array dimension '{dim}' in annotation '{value}'"
                            ))
                        })
                    })
                    .collect::<Result<Vec<usize>>>()?;
                let inner_type = Self::from_str(elem_str)?;
                Self::FixedArray(Box::new(inner_type), dims)
            }
            // Capitalized `typing` spellings of the PEP 585 builtin generics. A
            // forward-ref or external-IR string such as `List[int]` must lower like
            // `list[int]` when it does not name a generated local type. External-IR
            // conversion qualifies local shadowing names before this parser runs.
            g if g.ends_with(']') && g.starts_with("List[") => {
                Self::from_str(&["list", &g["List".len()..]].concat())?
            }
            g if g.ends_with(']') && g.starts_with("Dict[") => {
                Self::from_str(&["dict", &g["Dict".len()..]].concat())?
            }
            g if g.ends_with(']') && g.starts_with("Set[") => {
                Self::from_str(&["set", &g["Set".len()..]].concat())?
            }
            g if g.ends_with(']') && g.starts_with("FrozenSet[") => {
                Self::from_str(&["frozenset", &g["FrozenSet".len()..]].concat())?
            }
            g if g.ends_with(']') && g.starts_with("Tuple[") => {
                Self::from_str(&["tuple", &g["Tuple".len()..]].concat())?
            }
            g if g.ends_with(']') && g.starts_with("Type[") => {
                Self::from_str(&["type", &g["Type".len()..]].concat())?
            }
            dict if dict.starts_with("dict[") && dict.ends_with(']') => {
                let inner_types = dict
                    .strip_prefix("dict[")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix(']')
                    .unwrap_or_else(|| unreachable!());
                let inner_types = split_nonempty_top_level(inner_types, ',', true, "dict", value)?;
                // debug_assert_eq!(inner_types.len(), 2);
                let inner_types = inner_types
                    .iter()
                    .map(|x| Self::from_str(x))
                    .collect::<Result<Vec<_>>>()?;
                if inner_types.len() == 2 {
                    Self::PyDict {
                        key_type: Box::new(inner_types[0].clone()),
                        value_type: Box::new(inner_types[1].clone()),
                    }
                } else {
                    // A subscripted `dict[...]` with other than two arguments is
                    // malformed; surface it rather than silently emitting an untyped
                    // dict (mirrors the crate's "surface malformed IR" stance). A bare
                    // `dict` is still accepted as untyped by the arm below.
                    return Err(PyBindgenError::CodegenError(format!(
                        "Invalid dict annotation '{value}' \
                         (expected two type arguments, 'dict[<key>, <value>]')"
                    )));
                }
            }
            "dict" | "typing.Dict" | "typing_extensions.Dict" => Self::PyDict {
                key_type: Box::new(Self::Unknown),
                value_type: Box::new(Self::Unknown),
            },
            // `Mapping` is any mapping, not specifically a `dict`; a non-`dict` mapping
            // (`types.MappingProxyType`, a custom `collections.abc.Mapping`) fails
            // `Bound<PyDict>` extraction in return position. Degrade to `PyAny` -- which
            // also matches how subscripted `Mapping[...]` already resolves. `dict`/`Dict`
            // stay `PyDict`: every `dict` subclass passes `PyDict_Check`.
            "Mapping" => Self::PyAny,
            frozenset if frozenset.starts_with("frozenset[") && frozenset.ends_with(']') => {
                let inner = single_generic_argument(frozenset, "frozenset", true, "frozenset")?;
                let inner_type = Self::from_str(&inner)?;
                Self::PyFrozenSet(Box::new(inner_type))
            }
            "frozenset" | "typing.FrozenSet" | "typing_extensions.FrozenSet" => {
                Self::PyFrozenSet(Box::new(Self::Unknown))
            }
            list if list.starts_with("list[") && list.ends_with(']') => {
                let inner = single_generic_argument(list, "list", true, "list")?;
                let inner_type = Self::from_str(&inner)?;
                Self::PyList(Box::new(inner_type))
            }
            "list" | "typing.List" | "typing_extensions.List" => {
                Self::PyList(Box::new(Self::Unknown))
            }
            // `Sequence` is a protocol, not specifically a `list`: tuples, ranges, and
            // custom sequence implementations are all valid values but fail `PyList`
            // extraction. Keep both bare and parameterized spellings safely untyped.
            "Sequence" => Self::PyAny,
            sequence if sequence.starts_with("Sequence[") && sequence.ends_with(']') => {
                let _ = single_generic_argument(sequence, "Sequence", true, "Sequence")?;
                Self::PyAny
            }
            // (#16) `Iterable`/`Iterator` (subscripted or bare) map to `PyAny`, NOT
            // `Vec`/`PyList`: pyo3's `Vec` extraction rejects a generator (the canonical
            // iterator value), so lowering to `Vec` produced bindings that fail at
            // runtime on any real iterator. `PyAny` is the faithful, always-extractable
            // handle; the consumer can `try_iter()` it as needed.
            "Iterable" | "Iterator" => Self::PyAny,
            iterable if iterable.starts_with("Iterable[") && iterable.ends_with(']') => {
                let _ = single_generic_argument(iterable, "Iterable", true, "Iterable")?;
                Self::PyAny
            }
            iterator if iterator.starts_with("Iterator[") && iterator.ends_with(']') => {
                let _ = single_generic_argument(iterator, "Iterator", true, "Iterator")?;
                Self::PyAny
            }
            set if set.starts_with("set[") && set.ends_with(']') => {
                let inner = single_generic_argument(set, "set", true, "set")?;
                let inner_type = Self::from_str(&inner)?;
                Self::PySet(Box::new(inner_type))
            }
            "set" | "typing.Set" | "typing_extensions.Set" => Self::PySet(Box::new(Self::Unknown)),
            tuple if tuple.starts_with("tuple[") && tuple.ends_with(']') => {
                let inner_types = tuple
                    .strip_prefix("tuple[")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix(']')
                    .unwrap_or_else(|| unreachable!());
                let inner_types = split_nonempty_top_level(inner_types, ',', true, "tuple", value)?;
                let inner_types = inner_types
                    .iter()
                    .map(|x| Self::from_str(x))
                    .collect::<Result<_>>()?;
                Self::PyTuple(inner_types)
            }
            "tuple" | "typing.Tuple" | "typing_extensions.Tuple" => {
                Self::PyTuple(vec![Self::Unknown])
            }

            // Additional types - std
            "ipaddress.IPv4Address" => Self::IpV4Addr,
            "ipaddress.IPv6Address" => Self::IpV6Addr,
            "os.PathLike" | "pathlib.Path" => Self::Path,
            path_like if path_like.starts_with("os.PathLike[") && path_like.ends_with(']') => {
                let _ = single_generic_argument(path_like, "os.PathLike", true, "os.PathLike")?;
                Self::Path
            }
            "slice" => Self::PySlice,

            // Additional types - num-complex
            "complex" => Self::PyComplex,

            // Additional types - datetime
            #[cfg(not(Py_LIMITED_API))]
            "datetime.date" => Self::PyDate,
            #[cfg(not(Py_LIMITED_API))]
            "datetime.datetime" => Self::PyDateTime,
            "timedelta" | "datetime.timedelta" => Self::PyDelta,
            #[cfg(not(Py_LIMITED_API))]
            "datetime.time" => Self::PyTime,
            #[cfg(not(Py_LIMITED_API))]
            "datetime.tzinfo" => Self::PyTzInfo,

            // Python-specific types
            "capsule" => Self::PyCapsule,
            "cfunction" => Self::PyCFunction,
            #[cfg(not(Py_LIMITED_API))]
            "code" => Self::PyCode,
            "Ellipsis" | "..." => Self::PyEllipsis,
            #[cfg(all(not(Py_LIMITED_API), not(any(PyPy, GraalPy))))]
            "frame" => Self::PyFrame,
            "function" => Self::PyFunction {
                param_types: vec![Self::PyEllipsis],
                return_annotation: Box::new(Self::Unknown),
            },
            // `Callable`/`Callable[...]` denotes any callable object, not specifically a
            // `def`/`lambda`. `Bound<PyFunction>` only extracts real Python functions, so
            // a builtin, bound method, `functools.partial`, or callable instance fails
            // extraction in return position and is over-restricted in argument position.
            // Degrade to `PyAny` -- the faithful, always-extractable handle -- exactly as
            // for `Iterable`/`Iterator`. (The literal `"function"` above stays
            // `PyFunction`: that name is only produced for a genuine function type.)
            "Callable" | "callable" => Self::PyAny,
            callable if callable.starts_with("Callable[") && callable.ends_with(']') => Self::PyAny,
            "module" => Self::PyModule,
            #[cfg(not(PyPy))]
            "super" => Self::PySuper,
            "traceback" => Self::PyTraceback,
            // (#15) `type[X]` is a Python *type object* (a class), not an instance of
            // `X`. Unwrapping it to `X` made return-position extraction always fail (a
            // class object cannot be extracted as an instance) and forward-position
            // callers pass an instance where a class is expected. Map it to the Python
            // type object instead; the inner `X` carries no faithful Rust type here.
            typ if typ.starts_with("type[") && typ.ends_with(']') => {
                let _ = single_generic_argument(typ, "type", true, "type")?;
                Self::PyType
            }
            "type" | "typing.Type" | "typing_extensions.Type" => Self::PyType,

            // classes
            class if class.starts_with("<class '") && class.ends_with("'>") => Self::from_str(
                class
                    .strip_prefix("<class '")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix("'>")
                    .unwrap_or_else(|| unreachable!()),
            )?,

            // enums
            enume if enume.starts_with("<enum '") && enume.ends_with("'>") => Self::from_str(
                enume
                    .strip_prefix("<enum '")
                    .unwrap_or_else(|| unreachable!())
                    .strip_suffix("'>")
                    .unwrap_or_else(|| unreachable!()),
            )?,

            // typing
            builtins if builtins.starts_with("builtins.") => Self::from_str(
                builtins
                    .strip_prefix("builtins.")
                    .unwrap_or_else(|| unreachable!()),
            )?,
            typing if typing.starts_with("typing.") => Self::from_str(
                typing
                    .strip_prefix("typing.")
                    .unwrap_or_else(|| unreachable!()),
            )?,
            typing_extensions if typing_extensions.starts_with("typing_extensions.") => {
                Self::from_str(
                    typing_extensions
                        .strip_prefix("typing_extensions.")
                        .unwrap_or_else(|| unreachable!()),
                )?
            }

            // collections.abc
            collections_abc if collections_abc.starts_with("collections.abc.") => Self::from_str(
                collections_abc
                    .strip_prefix("collections.abc.")
                    .unwrap_or_else(|| unreachable!()),
            )?,
            // collections
            collections if collections.starts_with("collections.") => Self::from_str(
                collections
                    .strip_prefix("collections.")
                    .unwrap_or_else(|| unreachable!()),
            )?,

            // Forbidden types
            forbidden if crate::config::FORBIDDEN_TYPE_NAMES.contains(&forbidden) => Self::PyAny,

            // Other types, that might be known (custom types of modules)
            other => Self::Other(other.to_owned()),
        })
    }
}

fn validate_balanced_brackets(value: &str) -> Result<()> {
    let mut delimiters = Vec::new();
    let mut quote = None;
    let mut escaped = false;
    for character in value.chars() {
        if let Some(delimiter) = quote {
            if escaped {
                escaped = false;
            } else if character == '\\' {
                escaped = true;
            } else if character == delimiter {
                quote = None;
            }
            continue;
        }
        match character {
            '\'' | '"' => quote = Some(character),
            '[' | '(' | '{' => delimiters.push(character),
            ']' | ')' | '}' => {
                let expected = match character {
                    ']' => '[',
                    ')' => '(',
                    '}' => '{',
                    _ => unreachable!(),
                };
                if delimiters.pop() != Some(expected) {
                    return Err(PyBindgenError::CodegenError(format!(
                        "Unbalanced brackets in type annotation '{value}'"
                    )));
                }
            }
            _ => {}
        }
    }
    if quote.is_some() {
        Err(PyBindgenError::CodegenError(format!(
            "Unbalanced quotes in type annotation '{value}'"
        )))
    } else if delimiters.is_empty() {
        Ok(())
    } else {
        Err(PyBindgenError::CodegenError(format!(
            "Unbalanced brackets in type annotation '{value}'"
        )))
    }
}

/// Strip one complete quoted payload.
///
/// Matching first/last quotes are not enough: `'pkg.A' | 'pkg.B'` is a union of two
/// quoted forward references, not one outer-quoted annotation. Requiring no unescaped
/// matching quote inside also prevents `ForwardRef('X', module='m')` from being partially
/// unwrapped as the nonsensical type `X', module='m`.
fn strip_exact_quoted_payload(value: &str) -> Option<&str> {
    let bytes = value.as_bytes();
    if bytes.len() < 2 {
        return None;
    }
    let quote = *bytes.first()?;
    if !matches!(quote, b'\'' | b'"') || bytes.last() != Some(&quote) {
        return None;
    }

    let mut escaped = false;
    for byte in &bytes[1..bytes.len() - 1] {
        if escaped {
            escaped = false;
        } else if *byte == b'\\' {
            escaped = true;
        } else if *byte == quote {
            return None;
        }
    }
    (!escaped).then_some(&value[1..value.len() - 1])
}

/// Unwrap the textual spellings emitted for a `typing.ForwardRef` without evaluating
/// the annotation. Exact wrapper names and a single quoted payload are required, so
/// malformed/call-like strings safely fall through to the ordinary `Other` path.
fn strip_textual_forward_ref(value: &str) -> Option<&str> {
    [
        "ForwardRef",
        "typing.ForwardRef",
        "typing_extensions.ForwardRef",
    ]
    .iter()
    .find_map(|name| {
        let inner = value
            .strip_prefix(name)?
            .strip_prefix('(')?
            .strip_suffix(')')?
            .trim();
        strip_exact_quoted_payload(inner)
    })
}

/// Return the contents of an exact named `[...]` generic spelling.
fn strip_named_generic<'a>(value: &'a str, names: &[&str]) -> Option<&'a str> {
    names.iter().find_map(|name| {
        value
            .strip_prefix(name)?
            .strip_prefix('[')?
            .strip_suffix(']')
    })
}

/// Whether `s` contains `sep` outside nested delimiters and quoted strings.
///
/// Used to detect a **top-level** PEP 604 union `|` so a `|` nested inside a
/// container's type arguments (`dict[str, int | float]`) is not mistaken for a
/// top-level union operator.
fn has_top_level(s: &str, sep: char) -> bool {
    let mut depth: isize = 0;
    let mut quote = None;
    let mut escaped = false;
    for c in s.chars() {
        if let Some(delimiter) = quote {
            if escaped {
                escaped = false;
            } else if c == '\\' {
                escaped = true;
            } else if c == delimiter {
                quote = None;
            }
            continue;
        }
        match c {
            '\'' | '"' => quote = Some(c),
            '[' | '(' | '{' => depth += 1,
            ']' | ')' | '}' => depth -= 1,
            _ if c == sep && depth == 0 => return true,
            _ => {}
        }
    }
    false
}

/// Split `s` on `sep` occurrences outside nested delimiters and quoted strings.
///
/// Nested separators are preserved intact so the container arms can recurse into
/// them.
fn split_top_level(s: &str, sep: char) -> Vec<String> {
    let mut parts = Vec::new();
    let mut depth: isize = 0;
    let mut quote = None;
    let mut escaped = false;
    let mut current = String::new();
    for c in s.chars() {
        if let Some(delimiter) = quote {
            current.push(c);
            if escaped {
                escaped = false;
            } else if c == '\\' {
                escaped = true;
            } else if c == delimiter {
                quote = None;
            }
            continue;
        }
        match c {
            '\'' | '"' => {
                quote = Some(c);
                current.push(c);
            }
            '[' | '(' | '{' => {
                depth += 1;
                current.push(c);
            }
            ']' | ')' | '}' => {
                depth -= 1;
                current.push(c);
            }
            _ if c == sep && depth == 0 => {
                parts.push(current.trim().to_owned());
                current = String::new();
            }
            _ => current.push(c),
        }
    }
    parts.push(current.trim().to_owned());
    parts
}

/// Extract exactly one top-level type argument from `Name[...]`.
fn single_generic_argument(
    annotation: &str,
    name: &str,
    allow_trailing: bool,
    kind: &str,
) -> Result<String> {
    let inner = annotation
        .strip_prefix(name)
        .and_then(|value| value.strip_prefix('['))
        .and_then(|value| value.strip_suffix(']'))
        .unwrap_or_else(|| unreachable!("guarded by the caller's exact generic match"));
    let mut arguments = split_top_level(inner, ',');
    if allow_trailing && arguments.last().is_some_and(String::is_empty) {
        arguments.pop();
    }
    if arguments.len() != 1 || arguments[0].is_empty() {
        return Err(PyBindgenError::CodegenError(format!(
            "Invalid {kind} annotation '{annotation}' \
             (expected exactly one type argument)"
        )));
    }
    Ok(arguments.pop().unwrap_or_else(|| unreachable!()))
}

/// Split a generic argument list while rejecting missing operands.
///
/// Python subscriptions accept one trailing comma (`tuple[int,]`,
/// `dict[str, int,]`, `Union[int,]`), but an empty argument anywhere else is
/// malformed. Operators such as PEP 604 `|` opt out of trailing-comma handling,
/// so `int |` remains an error instead of being misread as `Optional[int]`.
fn split_nonempty_top_level(
    s: &str,
    sep: char,
    allow_trailing: bool,
    kind: &str,
    annotation: &str,
) -> Result<Vec<String>> {
    let mut parts = split_top_level(s, sep);
    if allow_trailing && parts.last().is_some_and(String::is_empty) {
        parts.pop();
    }
    if parts.is_empty() || parts.iter().any(String::is_empty) {
        return Err(PyBindgenError::CodegenError(format!(
            "Invalid {kind} annotation '{annotation}' (empty type argument)"
        )));
    }
    Ok(parts)
}

